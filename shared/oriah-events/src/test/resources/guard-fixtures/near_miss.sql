-- A near-miss copy of the reference SQL, loaded into its own schema by the
-- guard tests. Each difference below is one a hurried copy could make, and
-- each must be named by the guards. Without this fixture a guard that checks
-- nothing would pass every service.

CREATE OR REPLACE FUNCTION oriah_refuse_change() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '% is append-only: % refused', TG_TABLE_NAME, TG_OP;
END;
$$;

-- outbox: by-default identity whose sequence starts at 0 (the first row's
-- id is not above the cursor's starting 0) and hands out ids 20 at a time
-- per connection (so ids stop following commit order), actor nullable,
-- occurred_at defaulted, payload jsonb (re-formats the text), an extra
-- column, the per-aggregate UNIQUE missing, and no append-only triggers at
-- all.
CREATE TABLE outbox (
    outbox_id      BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 0 MINVALUE 0 CACHE 20) PRIMARY KEY,
    event_id       UUID NOT NULL UNIQUE,
    aggregate_type VARCHAR(64) NOT NULL,
    aggregate_id   VARCHAR(64) NOT NULL,
    seq            BIGINT NOT NULL,
    event_type     VARCHAR(128) NOT NULL,
    schema_version INT NOT NULL,
    topic          VARCHAR(128) NOT NULL,
    occurred_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    recorded_at    TIMESTAMPTZ NOT NULL DEFAULT now(),
    actor          VARCHAR(128),
    payload        JSONB NOT NULL,
    note           TEXT
);

-- The relay cursor without its 'main' seed row.
CREATE TABLE outbox_relay_cursor (
    relay          VARCHAR(64) PRIMARY KEY,
    last_outbox_id BIGINT NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL
);

-- processed_event: processed_at not defaulted, and only the row trigger, so
-- TRUNCATE still empties it.
CREATE TABLE processed_event (
    consumer     VARCHAR(64) NOT NULL,
    event_id     UUID NOT NULL,
    processed_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (consumer, event_id)
);

CREATE TRIGGER processed_event_append_only_row
    BEFORE UPDATE OR DELETE ON processed_event
    FOR EACH ROW EXECUTE FUNCTION oriah_refuse_change();

-- processed_aggregate: last_seq nullable, and a key that forgets the
-- aggregate type (an order and a product with the same id would collide).
CREATE TABLE processed_aggregate (
    consumer       VARCHAR(64) NOT NULL,
    aggregate_type VARCHAR(64) NOT NULL,
    aggregate_id   VARCHAR(64) NOT NULL,
    last_seq       BIGINT,
    PRIMARY KEY (consumer, aggregate_id)
);

