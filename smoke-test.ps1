Write-Host "[3/20] Customer: profile + address..." -ForegroundColor Cyan
Invoke-RestMethod -Method POST `
    -Uri "http://localhost:8080/api/v1/customers/me" `
    -Headers @{ Authorization="Bearer $alice" } | Out-Null
