$sku = "AUR-18K-" + ([guid]::NewGuid().ToString().Substring(0,8).ToUpper())

Write-Host "[1/20] JWTs..." -ForegroundColor Cyan
$maya  = Get-Jwt "maya"
$alice = Get-Jwt "alice"

Write-Host "[2/20] Admin: product + inventory..." -ForegroundColor Cyan
